@pytest.mark.parametrize("locale", ["en", "fr"])
def test_ftl_parses_cleanly(locale: str) -> None:
    """fluent_compiler accepts the file with no parse / runtime errors."""
    path = _TRANSLATIONS / locale / "pdf-checks.ftl"
    content = path.read_text(encoding="utf-8")
    bundle = FluentBundle.from_string(locale, content)
    errors = bundle.check_messages()
    assert not errors, (
        f"{locale}/pdf-checks.ftl has {len(errors)} parse error(s): "
        f"{errors[:3]}"
    )
